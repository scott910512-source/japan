/* 지금 새 버전으로 갈아끼우면 잃는 것이 있는가.
 *
 * ★ 저장된 것만 봐서는 모자란다 ★
 *
 * main.jsx는 「학습 중이면 갱신을 미룬다」고 정해 두고, 학습 중인지를
 * 회독 세션(localStorage의 jp_manabu_session_v1)으로 판단했다. 카드를
 * 판정하는 중에 화면이 새로 뜨는 일은 그것으로 막혔다.
 *
 * 그런데 그 뒤로 저장소에 안 남는 자리가 늘었다.
 *
 *   자동 듣기   판을 짜서 돌리는 중 — 어디까지 들었는지는 화면 안에만 있다
 *   시험        절반 푼 답 — 제출 전에는 아무 데도 안 적힌다
 *   N3 코스     풀던 문제와 고른 보기
 *
 * 이 자리들은 「세션이 없으니 끊길 게 없다」로 읽혔다. 그래서 배포가 올라온
 * 뒤 앱을 다시 앞으로 꺼내는 순간(visibilitychange) 화면이 통째로 새로 떴다.
 * 쓰는 사람에게는 「자꾸 튕기고 리셋된다」로 보인다 — 실제로 회독 기록은
 * 멀쩡한데, 하던 자리가 사라지니 기록까지 날아간 것처럼 느껴진다.
 *
 * 그래서 화면이 스스로 알린다. 들어갈 때 표시를 세우고 나갈 때 내린다.
 * 저장소가 아니라 메모리에 둔다 — 탭이 죽으면 같이 사라져야 하는 값이다.
 * 남아 있으면 영영 갱신이 안 되는데, 그건 이것보다 나쁘다. */
const busy = new Set();

export function markBusy(key, on) {
  if (on) busy.add(key);
  else busy.delete(key);
}

export function isBusy() {
  return busy.size > 0;
}

/* 지금 무엇 때문에 미루는지 — 디버깅과 검사에서 쓴다 */
export function busyKeys() {
  return [...busy];
}

/* 브라우저에서 들여다볼 창구. 「지금 왜 갱신을 미루나」를 밖에서 물을 길이
   없으면, 반대로 영영 안 미루는 버그와 영영 미루는 버그를 구별할 수가 없다.
   검사도 이걸로 본다 — 화면 안쪽 상태를 흉내 내지 않고 실제 값을 읽는다. */
if (typeof window !== 'undefined') window.__jpBusy = busyKeys;
