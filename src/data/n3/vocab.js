export const VOCAB_LESSON_SIZE = 15;

/* 태그로 주제를 정한다. 구체적인 주제를 먼저 본다 — 「일상」은 거의 모든
   단어에 붙어 있어서 맨 뒤에 둔다. 아무 태그도 안 맞으면 「상태·변화·추상」. */
function topicOf(word) {
  const tags = word.tags || [];
  for (const t of VOCAB_TOPICS) {
    if (t.tags.some((x) => tags.includes(x))) return t.id;
  }
  return 'abstract';
}

const N3_POOL = ALL_WORDS.filter((w) => w.level === 'N3');

const grouped = new Map(VOCAB_TOPICS.map((t) => [t.id, []]));
for (const w of N3_POOL) grouped.get(topicOf(w)).push(w);

export const VOCAB_LESSONS = VOCAB_TOPICS.flatMap((t) => {
  const words = grouped.get(t.id);
  const out = [];
  for (let i = 0; i < words.length; i += VOCAB_LESSON_SIZE) {
    const n = out.length + 1;
    out.push({
      id: `v:${t.id}-${n}`,
      topic: t.id,
      title: `${t.title} ${n}`,
      emoji: t.emoji,
      words: words.slice(i, i + VOCAB_LESSON_SIZE),
    });
  }
  return out;
});

const lessonById = new Map(VOCAB_LESSONS.map((l) => [l.id, l]));
export const vocabLessonById = (id) => lessonById.get(id) || null;

export const VOCAB_WORDS = VOCAB_LESSONS.flatMap((l) => l.words.map((w) => ({ ...w, lessonId: l.id, topic: l.topic })));
const wordById = new Map(VOCAB_WORDS.map((w) => [w.id, w]));
export const vocabWordById = (id) => wordById.get(id) || null;

export function vocabOfTopic(topicId) {
  return VOCAB_LESSONS.filter((l) => l.topic === topicId);
}

