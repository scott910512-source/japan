/* 여행 일본어 코스 — 단원 → 레슨 → 한 줄.
 *
 * ★ 왜 따로 있나 ★
 *
 * 공항·택시·호텔·식당에서 「대충은 알아들었는데」가 이 코스의 출발점이다.
 * 상황별 회화(situations.js)는 내가 할 말이 앞이고 상대 대답이 뒤에 붙는
 * 모양이라, 정작 현지에서 막히는 쪽 — 직원이 먼저 던지는 말 — 이 연습의
 * 중심에 없었다. 여기서는 줄마다 누가 말하는지(who)를 적고, 직원 줄은
 * 「듣고 알아듣기」로, 내 줄은 「뜻 보고 말하기」로 연습한다.
 *
 * 삿포로 벼락치기(sapporo.js)와는 다르다. 그건 한 여행의 낱말 목록이고,
 * 이건 어느 여행에서나 겪는 장면의 말이다. 지명이 들어갈 자리는 〇〇로 둔다.
 *
 * 한 줄:
 *   who   staff(직원·승무원·점원·역무원) | me(나)
 *   jp    일본어 (화면에 보이는 것)
 *   kana  읽기 (소리는 늘 이쪽으로 낸다 — 한자 읽기를 기기에 맡기지 않는다)
 *   ko    뜻
 *   note  이 말이 나오는 자리, 대답하는 요령 — 있을 때만
 *
 * 단원 차례는 여행에서 부딪히는 차례다. 레슨 하나는 열 줄 안팎 — 한 자리에서
 * 실제로 오가는 만큼만. */

const S = (id, jp, kana, ko, note) => ({ id, who: 'staff', jp, kana, ko, ...(note ? { note } : {}) });
const M = (id, jp, kana, ko, note) => ({ id, who: 'me', jp, kana, ko, ...(note ? { note } : {}) });

