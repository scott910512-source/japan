export const TRAVEL_LESSONS = TRAVEL_UNITS.flatMap((u) => u.lessons.map((l) => ({ ...l, unitId: u.id, unitTitle: u.title })));
export const TRAVEL_ITEMS = TRAVEL_LESSONS.flatMap((l) => l.items.map((it) => ({ ...it, lessonId: l.id, unitId: l.unitId })));

export function lessonById(id) {
  return TRAVEL_LESSONS.find((l) => l.id === id) || null;
}
export function unitById(id) {
  return TRAVEL_UNITS.find((u) => u.id === id) || null;
}
export function itemsOfLesson(id) {
  return TRAVEL_ITEMS.filter((it) => it.lessonId === id);
}
export function itemsOfUnit(id) {
  return TRAVEL_ITEMS.filter((it) => it.unitId === id);
}
