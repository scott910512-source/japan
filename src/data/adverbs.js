/* 부사 빈칸 채우기 — 문제 자료.
 *
 * 부사는 뜻만 외워서는 안 늘어난다. 「あまり = 별로」를 알아도 「あまり
 * わかります」라고 쓰면 틀린다 — 부사의 절반은 뜻이 아니라 「어디에 붙고
 * 뒤에 뭐가 오는가」다. 그건 문장 안에서만 배워진다.
 *
 * 이 자료를 만들 때 지킨 규칙 하나: 답이 하나만 되게 문장을 짠다.
 *
 * 이게 제일 어렵고 제일 중요하다. 「毎日【　】走ります」에 いつも도 よく도
 * 다 되면, 맞는 답을 골랐는데 틀렸다고 나온다. 그러면 사람이 앱을 안 믿는다.
 * 그래서 답을 하나로 묶어 주는 장치를 문장에 넣었다.
 *
 *   · 부정 호응 — あまり·ぜんぜん·めったに는 뒤에 부정이 온다
 *   · 짝 — まだ〜ていません / もう〜ました
 *   · 숫자·빈도 — 「週に一回」처럼 앞뒤에 못 박는 말을 둔다
 *   · 이미 일어난 일 / 아직 안 일어난 일
 *
 * 확신이 안 서는 문장은 아예 뺐다. 틀린 걸 자신 있게 가르치는 게 제일 나쁘다.
 *
 * 빈칸은 【 】로 적는다. 화면이 이걸 찾아 칸으로 바꾼다. */

