/* 일상문법 — 매일 쓰는 자리에 무엇을 넣는가.
 *
 * 기초문법(문법 카드)은 「て형은 이렇게 만든다」처럼 규칙을 외우는 자리다.
 * 그런데 여행에서 막히는 건 규칙을 몰라서가 아니라 자리를 몰라서다.
 * 「電車を乗ります」라고 말하는 사람은 を의 뜻을 몰라서 그런 게 아니라,
 * 乗る가 に를 받는다는 걸 문장 안에서 안 만나 봐서 그렇다.
 *
 * 그래서 여기는 빈칸 채우기로만 간다. 부사 연습과 같은 방식이고, 같은 원칙을
 * 지킨다 — ★ 답이 하나만 되게 문장을 짠다 ★. 보기 셋 중 둘도 말이 되면
 * 그건 문제가 아니라 함정이고, 배우는 게 아니라 찍는 게 된다.
 *
 * 틀렸을 때 왜 틀렸는지를 반드시 적는다. 정답만 알려 주면 다음에 또 틀린다. */

